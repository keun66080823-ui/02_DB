/*4. 주문 정보 테이블 (ORDERS)
주문 번호 (ORDER_ID) - NUMBER [PK]
주문일 (ORDER_DATE) - DATE [DEFAULT SYSDATE]
처리상태 (STATUS) - CHAR(1) DEFAULT 'N' [CHECK ('Y', 'N') ]
고객 ID (CUSTOMER_ID) - NUMBER [FK - CUSTOMERS(CUSTOMER_ID) ON DELETE CASCADE]
 * */

CREATE TABLE ORDERS(
	ORDER_ID NUMBER PRIMARY KEY,
	ORDER_DATE DATE DEFAULT SYSDATE,
	STATUS CHAR(1) DEFAULT 'N' CONSTRAINT STATUS_CHECK CHECK(STATUS IN ('Y', 'N')),
	CUSTOMER_ID NUMBER CONSTRAINT CUSTOMER_ID_FK REFERENCES CUSTOMERS ON DELETE CASCADE
);

